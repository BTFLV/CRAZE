// The material library uses German names as identifiers (they are stored in projects).
const MATERIAL_EN: Record<string, string> = {
  Chrom: "Chromium",
  Kupfer: "Copper",
  Molybdän: "Molybdenum",
  Platin: "Platinum",
  Silber: "Silver",
  Tantal: "Tantalum",
  Titan: "Titanium",
  Wolfram: "Tungsten",
};

/** Display name of a library material in the current language. */
export function materialName(name: string): string {
  return store.lang === "en" ? (MATERIAL_EN[name] ?? name) : name;
}

export function t(key: string, params?: Record<string, string | number>): string {
  const parts = key.split(".");
  let v: unknown = dicts[store.lang];
  for (const p of parts) v = (v as Record<string, unknown>)?.[p];
  let s = typeof v === "string" ? v : key;
  if (params) for (const [k, val] of Object.entries(params)) s = s.replaceAll(`{${k}}`, String(val));
  return s;
}
